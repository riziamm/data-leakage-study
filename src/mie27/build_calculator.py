"""Fit optimism(n, k_mean, icc, p, model) and write runs/<run_id>/calculator.py.

Surface (per model x p), fitted to cell-mean (a)-(c) optimism from the scenarios
with a plain patient -> rows structure: control (k = 1), S1_r1_d0 (k = 2: one row per
eye with concordant labels is identical in distribution to a k = 2 patient cluster,
since the eye effect is indistinguishable from row noise), S2_k4, S2_k8, S3 (k ~ 5):

    optimism = icc * (1 - 1/k) * poly2(icc, ln n, ln k, true_auc)

The prefactor forces optimism = 0 at ICC = 0 and at k = 1, where it is zero by
construction. Other S1 variants are excluded: with r = 2 the eye level adds a
second clustering layer, and with d = 0.2 labels differ within a patient, so neither
is a function of k_mean alone (DECISIONS.md D6).

    python -m mie27.build_calculator --run-id v1
"""
from __future__ import annotations

import argparse
import itertools
import json
from pathlib import Path

import numpy as np
import pandas as pd

SCEN = ["control", "S1_r1_d0", "S2_k4", "S2_k8", "S3"]
RIDGE = 1e-6


def design(n, k, icc, auc):
    n, k, icc, auc = map(np.atleast_1d, map(np.asarray, (n, k, icc, auc)))
    v = [icc, np.log(n), np.log(k), auc]
    cols = [np.ones_like(icc)] + v + [a * b for a, b in itertools.combinations_with_replacement(v, 2)]
    return np.column_stack(cols) * (icc * (1 - 1 / k))[:, None]


def fit(df: pd.DataFrame):
    X = design(df.n, df.k_mean, df.icc, df.true_auc)
    y = df.optimism_mean.to_numpy()
    A = X.T @ X + RIDGE * np.eye(X.shape[1])
    coef = np.linalg.solve(A, X.T @ y)
    yhat = X @ coef
    H = X @ np.linalg.solve(A, X.T)
    loo = (y - yhat) / (1 - np.clip(np.diag(H), None, 0.999))
    return coef, dict(n_cells=len(y), rmse=float(np.sqrt(np.mean((y - yhat) ** 2))),
                      max_abs=float(np.max(np.abs(y - yhat))),
                      loo_rmse=float(np.sqrt(np.mean(loo ** 2))),
                      mc_se_mean=float(df.optimism_mcse.mean()))


TEMPLATE = '''"""Optimism calculator - generated by mie27.build_calculator. Do not edit.

run_id: {run_id} | git: {ghash} | replicates/cell: {n_reps}
optimism = expected AUC(row-level CV) - AUC(patient-level CV), fold-mean AUC.

Valid only inside the simulated grid; anything outside raises ValueError:
  n in [20, 200], k_mean in [1, 8], icc in [0, 0.9], p in {{20, 180}},
  true_auc in [0.5, 0.8], model in {models}.
Fit error per (model, p): see FIT_ERROR (RMSE / LOO-RMSE / max |error| in AUC units).
"""
import itertools
import math

COEF = {coef}
FIT_ERROR = {fit_error}
BOUNDS = dict(n=(20, 200), k_mean=(1.0, 8.0), icc=(0.0, 0.9), true_auc=(0.5, 0.8))


def _design(n, k, icc, auc):
    v = [icc, math.log(n), math.log(k), auc]
    cols = [1.0] + v + [a * b for a, b in itertools.combinations_with_replacement(v, 2)]
    return [c * icc * (1 - 1 / k) for c in cols]


def optimism(n, k_mean, icc, p, model, *, true_auc=0.65):
    """Expected optimism of row-level over patient-level CV, in AUC units.

    true_auc defaults to 0.65 (the grid midpoint); pass it explicitly when known.
    """
    model = str(model).lower()
    key = f"{{model}}|{{int(p)}}"
    if key not in COEF:
        raise ValueError(f"model/p {{key!r}} not in the simulated grid; fitted: {{sorted(COEF)}}")
    for name, val in dict(n=n, k_mean=k_mean, icc=icc, true_auc=true_auc).items():
        lo, hi = BOUNDS[name]
        if not (lo <= val <= hi):
            raise ValueError(f"{{name}} = {{val}} outside simulated range [{{lo}}, {{hi}}]; "
                             "refusing to extrapolate")
    return sum(c * x for c, x in zip(COEF[key], _design(n, k_mean, icc, true_auc)))


if __name__ == "__main__":
    for k, e in FIT_ERROR.items():
        print(k, e)
'''


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-id", required=True)
    ap.add_argument("--runs-dir", default="runs")
    a = ap.parse_args(argv)
    run_dir = Path(a.runs_dir) / a.run_id
    res = pd.read_csv(run_dir / "results.csv")
    d = res[(res.split == "a_row") & res.scenario.isin(SCEN)]
    coef, errs, val = {}, {}, []
    for (m, p), g in d.groupby(["model", "p"]):
        # held-out validation: 20% of cells (seeded), fit on the rest, score the held-out
        rng = np.random.default_rng(2027)
        hold = rng.random(len(g)) < 0.2
        if hold.sum() >= 3 and (~hold).sum() >= 20:
            c_tr, _ = fit(g[~hold])
            h = g[hold]
            pred = design(h.n, h.k_mean, h.icc, h.true_auc) @ c_tr
            err = pred - h.optimism_mean.to_numpy()
            val.append(dict(model=m, p=p, n_heldout=int(hold.sum()),
                            heldout_rmse=float(np.sqrt(np.mean(err ** 2))),
                            heldout_max_abs=float(np.max(np.abs(err))),
                            heldout_mc_se_mean=float(h.optimism_mcse.mean())))
        c, e = fit(g)
        coef[f"{m}|{p}"] = [round(float(x), 10) for x in c]
        errs[f"{m}|{p}"] = {k: round(v, 5) if isinstance(v, float) else v for k, v in e.items()}
    src = TEMPLATE.format(run_id=a.run_id, ghash=str(res.git_hash.iloc[0])[:12],
                          n_reps=int(res.n_reps.min()), models=sorted(d.model.unique()),
                          coef=json.dumps(coef, indent=1), fit_error=json.dumps(errs, indent=1))
    (run_dir / "calculator.py").write_text(src)
    pd.DataFrame(errs).T.rename_axis("model|p").to_csv(run_dir / "calculator_fit_error.csv")
    print("in-sample / LOO fit error:\n" + pd.DataFrame(errs).T.to_string())
    if val:
        v = pd.DataFrame(val)
        v.to_csv(run_dir / "calculator_validation.csv", index=False)
        print("\nheld-out validation (20% of cells):\n" + v.to_string(index=False))


if __name__ == "__main__":
    main()
